/** Encode text as Windows-1252 bytes the way Traverse PC writes it (the
 *  fixture only uses Latin-1 characters, so this is one byte per char). */
export function toWindows1252Bytes(text: string): Uint8Array {
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c > 0xff) throw new Error(`not Latin-1: U+${c.toString(16)}`);
    out[i] = c;
  }
  return out;
}
