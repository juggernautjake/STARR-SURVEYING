// scripts/dump-missing-schema.mjs
//
// Reconstructs `CREATE TABLE` DDL for every public table that the app queries
// but that has no CREATE statement anywhere in `seeds/`. See
// docs/planning/PLATFORM_AUDIT_AND_LAUNCH_QUESTIONS_2026-07-29.md §1.1 — the
// central business tables (`jobs`, `job_time_entries`, `payroll_runs`, …) only
// ever existed in the live database, so the repo could not stand up an
// environment.
//
// Reads SUPABASE_DB_URL from .env.local. Read-only against production — it
// issues nothing but catalog SELECTs.
//
// ORDERING. The output is deliberately split across two seed files, because
// 29 existing seeds (starting at 001_config.sql) ALTER these tables, while the
// reconstructed foreign keys point at tables that later seeds create:
//
//   seeds/000_baseline_tables.sql  — tables + indexes. Must run FIRST, so the
//                                    ALTERs in 001…463 have something to alter.
//   seeds/499_baseline_fks.sql     — foreign keys. Must run LAST, once every
//                                    referenced table (conversations, vehicles,
//                                    receipts, organizations, …) exists.
//
//   node scripts/dump-missing-schema.mjs            # write both seed files
//   node scripts/dump-missing-schema.mjs --all      # every public table
//   node scripts/dump-missing-schema.mjs --list     # names only, no DDL

import fs from 'node:fs';
import path from 'node:path';
import pg from 'pg';

const ROOT = process.cwd();
const ARGS = new Set(process.argv.slice(2));

// ── Which tables does the code touch? ──────────────────────────────────────
function walk(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.next' || e.name === '.git') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (/\.(ts|tsx)$/.test(e.name)) acc.push(p);
  }
  return acc;
}

function tablesUsedInCode() {
  const files = ['app', 'lib', 'worker', 'server', 'scripts']
    .filter((d) => fs.existsSync(path.join(ROOT, d)))
    .flatMap((d) => walk(path.join(ROOT, d)));
  const used = new Set();
  for (const f of files) {
    const s = fs.readFileSync(f, 'utf8');
    for (const m of s.matchAll(/\.from\(\s*['"`]([a-z_0-9]+)['"`]\s*\)/g)) used.add(m[1]);
  }
  return used;
}

function tablesDefinedInSeeds() {
  const dir = path.join(ROOT, 'seeds');
  const defined = new Set();
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.sql'))) {
    const s = fs.readFileSync(path.join(dir, f), 'utf8');
    const re = /CREATE\s+(?:TABLE|(?:MATERIALIZED\s+)?VIEW|OR\s+REPLACE\s+VIEW)\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?"?([a-z_0-9]+)"?/gi;
    for (const m of s.matchAll(re)) defined.add(m[1].toLowerCase());
  }
  return defined;
}

// ── DDL rendering ──────────────────────────────────────────────────────────
const ident = (n) => (/^[a-z_][a-z0-9_]*$/.test(n) ? n : `"${n}"`);

function columnLine(c) {
  let type = c.formatted_type;
  // Serial columns present as integer + a nextval default; keep both explicit
  // rather than collapsing to `serial` so the default's sequence name survives.
  let line = `  ${ident(c.column_name)} ${type}`;
  if (c.column_default !== null) line += ` DEFAULT ${c.column_default}`;
  if (c.is_nullable === 'NO') line += ' NOT NULL';
  return line;
}

async function main() {
  const envPath = path.join(ROOT, '.env.local');
  if (!fs.existsSync(envPath)) throw new Error('.env.local not found');
  const env = fs.readFileSync(envPath, 'utf8');
  const m = env.match(/SUPABASE_DB_URL\s*=\s*"?([^"\n\r]+)"?/);
  if (!m) throw new Error('SUPABASE_DB_URL not set in .env.local');

  const client = new pg.Client({
    connectionString: m[1].trim(),
    ssl: { rejectUnauthorized: false },
  });
  await client.connect();

  const live = await client.query(`
    select table_name
      from information_schema.tables
     where table_schema = 'public' and table_type = 'BASE TABLE'
     order by table_name
  `);
  const liveNames = live.rows.map((r) => r.table_name);

  let targets;
  if (ARGS.has('--all')) {
    targets = liveNames;
  } else {
    const used = tablesUsedInCode();
    const defined = tablesDefinedInSeeds();
    targets = liveNames.filter((t) => used.has(t) && !defined.has(t));
  }

  if (ARGS.has('--list')) {
    console.log(targets.join('\n'));
    console.error(`\n${targets.length} table(s).`);
    await client.end();
    return;
  }

  const PREAMBLE = [
    '-- Schema reconstruction for tables that existed ONLY in the live database.',
    '-- GENERATED by scripts/dump-missing-schema.mjs — do not hand-edit; regenerate.',
    '-- Verified column-for-column against production by scripts/verify-baseline-schema.mjs.',
    '--',
    '-- Background: docs/planning/PLATFORM_AUDIT_AND_LAUNCH_QUESTIONS_2026-07-29.md §1.1.',
    '-- 78 tables the app queries every day — including `jobs`, the central business entity —',
    '-- had no CREATE statement anywhere in seeds/. They were only ever ALTERed (seeds',
    '-- 280/304/306/452), so a fresh database could not be built from this repo, there was no',
    '-- way to stand up staging, and every schema change was an undocumented dashboard click.',
    '--',
    '-- Every statement is idempotent, so applying this to the existing production database is',
    '-- a no-op. Guarded by __tests__/schema-coverage.test.ts.',
  ];

  const out = [];
  out.push('-- seeds/000_baseline_tables.sql');
  out.push('--');
  out.push(...PREAMBLE);
  out.push('--');
  out.push('-- RUNS FIRST. 29 later seeds (from 001_config.sql onward) ALTER these tables, so they');
  out.push('-- must exist before any of them apply. Foreign keys are NOT here — they point at');
  out.push('-- tables created by later seeds and live in seeds/499_baseline_fks.sql.');
  out.push('');

  const fkStatements = [];
  const indexStatements = [];

  for (const table of targets) {
    // Columns
    const cols = await client.query(
      `select column_name,
              is_nullable,
              column_default,
              format_type(a.atttypid, a.atttypmod) as formatted_type
         from information_schema.columns c
         join pg_attribute a
           on a.attrelid = to_regclass('public.' || quote_ident(c.table_name))
          and a.attname  = c.column_name
        where c.table_schema = 'public' and c.table_name = $1
        order by c.ordinal_position`,
      [table],
    );

    // Constraints (PK / UNIQUE / CHECK inline; FK deferred to the end)
    const cons = await client.query(
      `select con.conname,
              con.contype,
              pg_get_constraintdef(con.oid) as def
         from pg_constraint con
         join pg_class rel on rel.oid = con.conrelid
         join pg_namespace ns on ns.oid = rel.relnamespace
        where ns.nspname = 'public' and rel.relname = $1
        order by con.contype, con.conname`,
      [table],
    );

    const inline = [];
    for (const c of cons.rows) {
      if (c.contype === 'f') {
        // Only `duplicate_object` is swallowed (makes re-runs a no-op). A missing
        // referenced table (`undefined_table`) must NOT be caught — that means the
        // seed order is wrong, and silently skipping the constraint would ship a
        // database with no referential integrity and no warning.
        fkStatements.push(
          `DO $$ BEGIN\n` +
            `  ALTER TABLE public.${ident(table)} ADD CONSTRAINT ${ident(c.conname)} ${c.def};\n` +
            `EXCEPTION WHEN duplicate_object THEN NULL; END $$;`,
        );
      } else if (c.contype === 'p' || c.contype === 'u' || c.contype === 'c') {
        inline.push(`  CONSTRAINT ${ident(c.conname)} ${c.def}`);
      }
    }

    // Indexes that aren't already implied by a PK/UNIQUE constraint
    const idx = await client.query(
      `select indexname, indexdef
         from pg_indexes
        where schemaname = 'public' and tablename = $1
        order by indexname`,
      [table],
    );
    const consNames = new Set(cons.rows.map((c) => c.conname));
    for (const i of idx.rows) {
      if (consNames.has(i.indexname)) continue;
      indexStatements.push(
        i.indexdef.replace(/^CREATE (UNIQUE )?INDEX /, (_, u) => `CREATE ${u || ''}INDEX IF NOT EXISTS `) + ';',
      );
    }

    const body = [...cols.rows.map(columnLine), ...inline].join(',\n');
    out.push(`-- ── ${table} ${'─'.repeat(Math.max(0, 66 - table.length))}`);
    out.push(`CREATE TABLE IF NOT EXISTS public.${ident(table)} (`);
    out.push(body);
    out.push(');');
    out.push('');
  }

  if (indexStatements.length) {
    out.push('');
    out.push('-- ── Indexes ──────────────────────────────────────────────────────────');
    out.push(...indexStatements);
    out.push('');
  }

  const fks = [];
  fks.push('-- seeds/499_baseline_fks.sql');
  fks.push('--');
  fks.push(...PREAMBLE);
  fks.push('--');
  fks.push('-- RUNS LAST (before the 500-block). These foreign keys reference tables created across');
  fks.push('-- the whole seed range — conversations, organizations, receipts, vehicles, job_files,');
  fks.push('-- kb_articles, problem_templates and others — so every one of them must already exist.');
  fks.push('--');
  fks.push('-- Each ALTER is wrapped so re-running is a no-op. `undefined_table` is NOT swallowed:');
  fks.push('-- a missing referenced table means the seed order is genuinely wrong and should fail');
  fks.push('-- loudly rather than silently ship a database with no referential integrity.');
  fks.push('');
  fks.push(...fkStatements);
  fks.push('');

  if (ARGS.has('--stdout')) {
    console.log(out.join('\n'));
    console.log(fks.join('\n'));
  } else {
    fs.writeFileSync(path.join(ROOT, 'seeds/000_baseline_tables.sql'), out.join('\n'), 'utf8');
    fs.writeFileSync(path.join(ROOT, 'seeds/499_baseline_fks.sql'), fks.join('\n'), 'utf8');
    console.log('Wrote seeds/000_baseline_tables.sql + seeds/499_baseline_fks.sql');
  }
  console.error(
    `Reconstructed ${targets.length} table(s), ${indexStatements.length} index(es), ${fkStatements.length} foreign key(s).`,
  );

  await client.end();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
